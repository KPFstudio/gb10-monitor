let current = 'en';

// Saved preference first, then the browser's languages; anything not Japanese reads as English.
export function detectLanguage(storage, navigatorRef) {
  try {
    const saved = storage?.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'ja') return saved;
  } catch {}
  // The browser's first (preferred) language decides; anything not Japanese reads as English.
  const preferred = String([...(navigatorRef?.languages ?? []), navigatorRef?.language].filter(Boolean)[0] ?? '').trim();
  return /^ja\b/i.test(preferred) ? 'ja' : 'en';
}

export function currentLanguage() {
  return current;
}

// Fills {placeholders}; missing values render as-is so a broken template is visible, never silent.
export function t(key, values) {
  const template = MESSAGES[current]?.[key] ?? MESSAGES.en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (values[name] === undefined ? match : String(values[name])));
}

export function setLanguage(language) {
  current = LANGS.includes(language) ? language : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current === 'ja' ? 'ja' : 'en';
  if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent('langchange', { detail: current }));
  return current;
}

// Browser-only: pick the language once and remember manual choices. Importing this module in Node never touches storage.
export function initLanguage(storage = typeof localStorage !== 'undefined' ? localStorage : undefined, navigatorRef = typeof navigator !== 'undefined' ? navigator : undefined) {
  current = detectLanguage(storage, navigatorRef);
  setLanguage(current);
  return current;
}

export function saveLanguage(language, storage = typeof localStorage !== 'undefined' ? localStorage : undefined) {
  try { storage?.setItem(LANG_KEY, language); } catch {}
}

// Locale for calendar labels, matching the UI language.
export function localeName(language = current) {
  return language === 'ja' ? 'ja-JP' : 'en-US';
}
